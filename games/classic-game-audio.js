export function originalVoiceEnabled(options, cue) {
  return Boolean(cue?.option && options?.categories?.[cue.option] === true);
}
export function enabledOriginalChoices(game, options, slots) {
  return (originalAudioCatalog[game] || []).filter(c=>slots.includes(c.slot) && originalVoiceEnabled(options,c));
}
export function originalRollAnnouncement(game, dice, blocked, actor, viewer, options, random=Math.random) {
  if (!Array.isArray(dice) || dice.length!==2) return null;
  if (blocked) {
    if (game!=='acey-deucy' || Number(actor)!==Number(viewer)) return null;
    const choices=enabledOriginalChoices(game,options,['wav-aww','wav-awcrap','wav-dangit']);
    return choices.length ? choices[Math.min(choices.length-1,Math.floor(random()*choices.length))].slot : null;
  }
  if (dice[0]===6 && dice[1]===6) return 'wav-dblsix';
  if (game==='acey-deucy' && ((dice[0]===1 && dice[1]===2)||(dice[0]===2 && dice[1]===1))) return 'wav-aceydeucy';
  return null;
}
export function originalPlacementCue(before, after, viewer) {
  const a=before?.fleets?.[String(viewer)],b=after?.fleets?.[String(viewer)];
  if (after?.phase!=='placement' || JSON.stringify(a?.ships||[])===JSON.stringify(b?.ships||[])) return null;
  return after.lastPlacement?.operation==='auto-place' ? 'wav-locate' : 'wav-key';
}
export function originalReminderPlan(game, options) {
  if (game==='spades') return [
    {delay:0,slots:enabledOriginalChoices(game,options,['wav-yourturn']).map(c=>c.slot)},
    {delay:15080,slots:enabledOriginalChoices(game,options,['wav-yourturn2']).map(c=>c.slot)},
  ].filter(p=>p.slots.length);
  if (['backgammon-first-party','acey-deucy'].includes(game)) {
    const slots=enabledOriginalChoices(game,options,['wav-ygo','wav-ymove','wav-yturn','wav-ymove2']).map(c=>c.slot);
    return slots.length ? [{delay:10080,slots}] : [];
  }
  return [];
}

export function originalPointRoll(game, before, after) {
  if (!['backgammon-first-party','acey-deucy'].includes(game) || (after.history||[]).length!==(before.history||[]).length) return null;
  const noLegal=after.lastNoLegalMove||after.lastBlockedRoll;
  const blocked=noLegal && String(noLegal.kind||'whole-turn')==='whole-turn' && JSON.stringify(noLegal)!==JSON.stringify(before.lastNoLegalMove||before.lastBlockedRoll);
  const opening=(after.openingRollAttempts||[]).length>(before.openingRollAttempts||[]).length;
  const stage=game==='acey-deucy'?before.aceyStage:before.backgammonStage;
  const accepted=['roll','roll-again'].includes(stage) && (blocked || (after.remainingDice||[]).length>0);
  if (!opening&&!accepted) return null;
  const dice=opening?Object.values(after.openingRollAttempts.at(-1).rolls||{}):blocked?noLegal.dice:after.dice;
  if (!Array.isArray(dice)||dice.length!==2||dice.some(n=>!Number.isInteger(n)||n<1||n>6))return null;
  return {dice,blocked:Boolean(blocked),actorUserId:noLegal?.actorUserId};
}
